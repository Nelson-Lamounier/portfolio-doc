#!/usr/bin/env node
/**
 * generate-navigation.mjs
 *
 * Reads scripts/wiki-manifest.json (produced by fetch-wiki.mjs) and
 * generates src/lib/navigation.ts with a typed navigation array.
 *
 * The navigation structure is driven entirely by the wiki's index.md —
 * no manual edits to navigation.ts are needed when new pages are added.
 *
 * Preserves a fixed "Home" entry at the top pointing to /.
 */

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname    = path.dirname(fileURLToPath(import.meta.url))
const ROOT         = path.resolve(__dirname, '..')
const MANIFEST     = path.join(__dirname, 'wiki-manifest.json')
const NAV_OUT      = path.join(ROOT, 'src', 'lib', 'navigation.ts')

// ── helpers ──────────────────────────────────────────────────────────────────

function log(msg)   { console.log(`  ${msg}`) }
function logOk(msg) { console.log(`  ✓ ${msg}`) }

function escapeTs(str) {
  return str.replace(/'/g, "\\'")
}

// ── generator ─────────────────────────────────────────────────────────────

function generateNavigationTs(sections) {
  const header = `// AUTO-GENERATED by scripts/generate-navigation.mjs
// Source: wiki/index.md → S3 portfolio-docs/manifest.json → here
// Do not edit manually — run \`npm run wiki:fetch\` to regenerate.

export const navigation = [`

  const body = sections.map(section => {
    const links = section.links.map(link => {
      const desc = link.description
        ? `\n      // ${escapeTs(link.description.slice(0, 100))}`
        : ''
      return `    {${desc}
      title: '${escapeTs(link.title)}',
      href:  '${escapeTs(link.href)}',
    },`
    }).join('\n')

    return `  {
    title: '${escapeTs(section.title)}',
    links: [
${links}
    ],
  },`
  }).join('\n')

  const footer = `]
`

  return [header, body, footer].join('\n')
}

// ── entry point ───────────────────────────────────────────────────────────

function main() {
  console.log('\n🗺️   generate-navigation: building navigation.ts\n')

  if (!fs.existsSync(MANIFEST)) {
    console.error(`ERROR: ${MANIFEST} not found.`)
    console.error('       Run \`npm run wiki:fetch\` first.')
    process.exit(1)
  }

  const manifest = JSON.parse(fs.readFileSync(MANIFEST, 'utf8'))

  if (!manifest.sections?.length) {
    console.error('ERROR: manifest.json has no sections. Check index.md in the wiki.')
    process.exit(1)
  }

  // Prepend a fixed Home section
  const allSections = [
    {
      title: 'Overview',
      links: [
        { title: 'Home', href: '/' },
      ],
    },
    ...manifest.sections,
  ]

  const ts = generateNavigationTs(allSections)
  fs.writeFileSync(NAV_OUT, ts, 'utf8')

  logOk(`src/lib/navigation.ts — ${manifest.sections.length} sections, ${manifest.pageCount} pages`)
  log(`Source: ${manifest.source ?? 's3'} (generated ${manifest.generated})`)
  console.log()
}

main()
